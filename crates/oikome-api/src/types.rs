/// Where one Save To writes, and how plain files are named.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(tag = "kind", rename_all = "snake_case")]
pub enum SaveDestination {
    /// Real files on a place, opened by any application.
    Files {
        /// Registered storage name; this computer when absent.
        #[serde(default)]
        place: Option<String>,
        /// Absolute local folder, or a folder within the storage.
        path: String,
        /// Such as `{taken:yyyy}/{taken:MM}`.
        folder_rule: String,
        /// Such as `{taken:yyyy-MM-dd} {title}` or `{name}`.
        name_rule: String,
    },
    /// A detached collection with its originals and portfolio in snapshots.
    Space {
        name: String,
        /// Registered storage name; this computer when absent.
        #[serde(default)]
        storage: Option<String>,
        title: String,
        #[serde(default)]
        cover: Option<String>,
        #[serde(default)]
        captions: HashMap<String, String>,
    },
}

