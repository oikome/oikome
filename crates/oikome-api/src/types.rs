//! Requests and replies of the API, as JSON (camelCase fields) and as the
//! TypeScript types in `packages/api` (generated by the `bindings` test).
//! Rows are not here: they travel as Arrow IPC streams.

use serde::{Deserialize, Serialize};
use ts_rs::TS;

/// No arguments.
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize, TS)]
pub struct Empty {}

/// This node.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(rename_all = "camelCase")]
pub struct NodeInfo {
    /// The node's DID ("Your ID" in the apps); contacts add it to share with
    /// this node.
    pub did: String,
    /// The name the owner gave the data center; empty until they do.
    pub name: String,
    /// Oikome version.
    pub version: String,
    /// The data directory on this computer.
    pub data_dir: String,
    /// Whether the owner said they stored the recovery key.
    pub recovery_key_saved: bool,
    /// Where peers reach this node's Arrow Flight service (`https://ip:port`),
    /// when it is serving.
    pub flight_url: Option<String>,
}

/// `rename_node`: the data center's name.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(rename_all = "camelCase")]
pub struct NodeName {
    /// 1 to 64 characters.
    pub name: String,
}

/// The node's recovery key, as 14 groups of 4 characters. Whoever has it
/// can act as this node: show it only to the owner, never store it.
#[derive(Clone, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(rename_all = "camelCase")]
pub struct RecoveryKey {
    pub key: String,
}

impl std::fmt::Debug for RecoveryKey {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str("RecoveryKey(<redacted>)")
    }
}

/// What a Space holds and which engine runs it.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(rename_all = "snake_case")]
pub enum SpaceKind {
    Analytical,
    Transactional,
    /// Another node's Space, queried there or copied here.
    Remote,
}

/// A Space, as listed.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(rename_all = "camelCase")]
pub struct SpaceSummary {
    pub name: String,
    pub kind: SpaceKind,
    /// Storage: `iceberg`, `lance`, `sqlite`, `remote` or `replica`.
    pub format: String,
    pub readonly: bool,
    /// Contacts it is shared with now (active shares).
    pub shared_with: u32,
}

/// `create_space`: a new local Space.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(rename_all = "camelCase")]
pub struct NewSpace {
    /// Letters, digits, `_` or `-`, not starting with a digit.
    pub name: String,
    /// `analytical` (default) or `transactional`.
    #[serde(default)]
    #[ts(optional)]
    pub kind: Option<SpaceKind>,
}

/// Names one Space.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(rename_all = "camelCase")]
pub struct SpaceRef {
    pub space: String,
}

/// A table or a view.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(rename_all = "snake_case")]
pub enum RelationKind {
    Table,
    View,
}

/// A relation of a Space.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(rename_all = "camelCase")]
pub struct TableSummary {
    pub name: String,
    pub kind: RelationKind,
}

/// `read_rows`: a page of a table or view, as an Arrow IPC stream.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(rename_all = "camelCase")]
#[ts(optional_fields)]
pub struct ReadRows {
    pub space: String,
    pub table: String,
    /// Rows per page, 1 to 1000; default 100.
    #[serde(default)]
    pub limit: Option<u32>,
    /// Rows to skip.
    #[serde(default)]
    pub offset: Option<u64>,
}

/// `run_sql`: the owner's statements, separated by `;`, run in one session.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(rename_all = "camelCase")]
#[ts(optional_fields)]
pub struct RunSql {
    pub sql: String,
    /// Space that bare table names resolve against.
    #[serde(default)]
    pub space: Option<String>,
}

/// `run_sql` when the last statement returns no rows.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(rename_all = "camelCase")]
pub struct SqlDone {
    /// Rows written, when the statement reports it.
    pub rows_affected: Option<u64>,
}

/// Someone the owner shares with.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(rename_all = "camelCase")]
pub struct Contact {
    pub did: String,
    pub name: String,
    pub added_at_ms: u64,
}

/// `add_contact`, `rename_contact`.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(rename_all = "camelCase")]
pub struct ContactInput {
    pub did: String,
    pub name: String,
}

/// Names one contact.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(rename_all = "camelCase")]
pub struct DidRef {
    pub did: String,
}

/// `remove_contact`: the contact, and how many of its shares were revoked.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(rename_all = "camelCase")]
pub struct RemovedContact {
    pub contact: Contact,
    pub revoked_shares: u32,
}

/// `share_space`: let a contact read a whole Space.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(rename_all = "camelCase")]
#[ts(optional_fields)]
pub struct ShareSpace {
    pub space: String,
    /// The contact's DID.
    pub did: String,
    /// Also let them keep a copy that follows the Space (subscription);
    /// otherwise they can only query it here.
    #[serde(default)]
    pub allow_copy: Option<bool>,
    /// 1 to 366 days; default 365.
    #[serde(default)]
    pub expires_in_days: Option<u32>,
}

/// What a share lets the contact do.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(rename_all = "snake_case")]
pub enum ShareAccess {
    /// Query the Space on this node.
    Query,
    /// Query it, or keep a copy (subscribe).
    Copy,
}

/// Whether a share still works.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(rename_all = "snake_case")]
pub enum ShareStatus {
    Active,
    Expired,
    Revoked,
}

/// A share just made. `token` is shown this once: hand it to the contact,
/// who mounts the Space with it.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(rename_all = "camelCase")]
pub struct NewShare {
    pub id: String,
    pub space: String,
    pub did: String,
    pub access: ShareAccess,
    /// Seconds since the Unix epoch.
    pub expires_at: u64,
    pub token: String,
}

/// A share, as listed (never with its token).
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(rename_all = "camelCase")]
pub struct Share {
    pub id: String,
    pub space: String,
    pub did: String,
    /// The contact's name, if the DID is a contact.
    pub contact_name: Option<String>,
    pub access: ShareAccess,
    pub issued_at_ms: u64,
    /// Seconds since the Unix epoch.
    pub expires_at: u64,
    pub status: ShareStatus,
}

/// `list_shares`.
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(rename_all = "camelCase")]
#[ts(optional_fields)]
pub struct ListShares {
    /// Only shares of this Space.
    #[serde(default)]
    pub space: Option<String>,
}

/// Names one share.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(rename_all = "camelCase")]
pub struct ShareRef {
    pub id: String,
}

/// `revoke_share`.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(rename_all = "camelCase")]
pub struct RevokedShare {
    pub id: String,
    /// Whether this was the contact's last active share of the Space, so
    /// their grant on it was removed too.
    pub grant_removed: bool,
}

/// `list_access`: newest first.
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(rename_all = "camelCase")]
#[ts(optional_fields)]
pub struct ListAccess {
    /// The last id of the previous page.
    #[serde(default)]
    pub before_id: Option<i64>,
    /// 1 to 500; default 100.
    #[serde(default)]
    pub limit: Option<u32>,
    /// Only requests by this DID.
    #[serde(default)]
    pub did: Option<String>,
    /// Only requests naming this Space.
    #[serde(default)]
    pub space: Option<String>,
}

/// How a request ended.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(rename_all = "snake_case")]
pub enum AccessOutcome {
    Allowed,
    Denied,
    Failed,
}

/// One request a peer or a browser sent this node.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(rename_all = "camelCase")]
pub struct AccessItem {
    pub id: i64,
    pub at_ms: u64,
    /// The caller's DID; `null` when it could not be authenticated.
    pub did: Option<String>,
    pub contact_name: Option<String>,
    pub method: String,
    pub spaces: Vec<String>,
    /// The share (token id) that let it in.
    pub share_id: Option<String>,
    pub outcome: AccessOutcome,
    pub reason: Option<String>,
    /// Requests merged into this item (failed authentications in one minute).
    pub count: u64,
}
